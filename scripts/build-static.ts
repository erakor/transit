/**
 * Downloads the MTA static subway GTFS and writes src/data/subway.generated.ts.
 *
 *   npm run build:static                 # download from the MTA
 *   npm run build:static -- path/to.zip  # use a local zip
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { strFromU8, unzipSync } from "fflate";
import { buildSubwayData } from "../src/static/build.js";

export const GTFS_URL = "https://rrgtfsfeeds.s3.amazonaws.com/gtfs_subway.zip";
const WANTED = new Set(["routes.txt", "stops.txt", "trips.txt", "stop_times.txt", "transfers.txt", "feed_info.txt"]);
const OUT = fileURLToPath(new URL("../src/data/subway.generated.ts", import.meta.url));

async function loadZip(source: string | undefined): Promise<Uint8Array> {
  if (source) return new Uint8Array(await readFile(source));
  const res = await fetch(GTFS_URL, { signal: AbortSignal.timeout(60_000) });
  if (!res.ok) throw new Error(`GET ${GTFS_URL}: HTTP ${res.status}`);
  return new Uint8Array(await res.arrayBuffer());
}

const zip = await loadZip(process.argv[2]);
const entries = unzipSync(zip, { filter: (f) => WANTED.has(f.name.split("/").pop()!) });
const files: Record<string, string> = {};
for (const [name, bytes] of Object.entries(entries)) files[name.split("/").pop()!] = strFromU8(bytes);

const data = buildSubwayData(files);
const source =
  `// Generated by scripts/build-static.ts from the MTA static subway GTFS. Do not edit.\n` +
  `// Refresh with \`npm run build:static\` (the "Refresh static GTFS" workflow does this on a schedule).\n` +
  `import type { SubwayData } from "../static/types.js";\n\n` +
  `export const SUBWAY_DATA: SubwayData = ${JSON.stringify(data, null, 1)};\n`;
await writeFile(OUT, source);
console.log(
  `wrote ${OUT}: feed ${data.feedVersion}, ${Object.keys(data.routes).length} routes, ` +
    `${Object.keys(data.stops).length} stops, ${data.stations.length} stations, ${(source.length / 1024).toFixed(0)} KiB`,
);
